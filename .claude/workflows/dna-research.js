export const meta = {
  name: 'dna-research',
  description: 'Глубокий research интейка: веб-разведка ниши и конкурентов, сборка ДНК, проверка на выдумки и анти-гарантию',
  whenToUse: 'Запускается скиллом ai-diagnost на каждую платную глубокую диагностику. args: {segment, client, intake, competitors, niche, geo, mode}',
  phases: [
    { title: 'Разведка',  detail: 'ниша, гео, язык клиента, цены, шум — и по агенту на каждого конкурента' },
    { title: 'Углубление', detail: 'что конкурент реально доказывает против того, что обещает' },
    { title: 'Синтез',    detail: 'по агенту на артефакт: ДНК бизнеса, ДНК клиента, разрывы, AI-точки, оффер, вилка, вопросы' },
    { title: 'Проверка',  detail: 'три скептика: выдумки, анти-гарантия, полнота' },
    { title: 'Правка',    detail: 'клиентские артефакты переписываются с учётом находок скептиков' },
  ],
}

// ── вход ────────────────────────────────────────────────────────────────────
const A = args || {}
const SEG = A.segment === 'expert' ? 'expert' : 'business'
const WHO = SEG === 'expert' ? 'эксперт-практик' : 'владелец бизнеса'
const CLIENT = A.client || 'клиент'
const INTAKE = A.intake || ''
const PATH = A.intakePath || ''
const NICHE = A.niche || ''
const GEO = A.geo || ''
const MODE = A.mode === 'express' ? 'express' : 'full'
const COMPS = (A.competitors || []).slice(0, 5)

if (!INTAKE && !PATH) { log('❌ В args нет ни intake, ни intakePath — research без анкеты бессмысленен.'); return { error: 'no intake' } }

// ── общие правила для всех агентов ──────────────────────────────────────────
const RULES = `
ПРАВИЛА (нарушение = брак работы):
- Разметка достоверности обязательна у каждого утверждения: ФАКТ (слова клиента из интейка) ·
  ФАКТ (веб) (нашёл в открытых источниках, с URL) · 🔷 АНАЛИЗ (твой вывод) ·
  ⚠️ ГИПОТЕЗА (нужна проверка на созвоне) · 🟥 ОТКРЫТО (данных нет).
- НЕ ВЫДУМЫВАТЬ. Нет данных — ставь 🟥, а не правдоподобную догадку. Это платная диагностика,
  клиент проверит каждое утверждение о себе.
- АНТИ-ГАРАНТИЯ: никаких обещаний цифр и сроков результата («+30%», «в 2 раза», «за месяц»).
  Только направление: продажи вырастут / затраты упадут / вас станет видно.
- Тексты конкурентов не копировать, пересказывать своими словами. НО если ставишь чужую фразу
  в кавычки — она должна быть ДОСЛОВНО из блока разведки, символ в символ.
- ЗАПРЕТ НА НОВЫЕ ВЕБ-ФАКТЫ: ты не ходишь в интернет. Любая метка ФАКТ (веб) допустима, только если
  это утверждение дословно есть в переданном тебе блоке разведки. Номера лицензий, рейтинги, годы
  основания, количество отзывов, слоганы — если их нет в разведке, их нет вообще. Ставь 🟥, а не
  правдоподобное число: выдуманный проверяемый идентификатор клиент раскроет за десять секунд.
- Тон: как оператор с оператором, без канцелярита и воды.
- Веб недоступен — так и напиши, не подменяй поиск фантазией.`

const CTX = `Клиент: ${CLIENT}. Сегмент: ${WHO}.${NICHE ? ` Ниша: ${NICHE}.` : ''}${GEO ? ` Гео: ${GEO}.` : ''}`
const SRC = INTAKE
  ? `ИНТЕЙК КЛИЕНТА (единственный источник его фактов):\n${INTAKE}`
  : `ИНТЕЙК КЛИЕНТА — единственный источник его фактов. ПЕРВЫМ ДЕЙСТВИЕМ прочитай файл целиком инструментом Read:\n${PATH}`
const FULL = `${CTX}\n\n${SRC}\n${RULES}`

const NOTES = {
  type: 'object', additionalProperties: false,
  properties: {
    findings: { type: 'array', items: { type: 'object', additionalProperties: false,
      properties: {
        claim:  { type: 'string' },
        layer:  { type: 'string', enum: ['ФАКТ', 'ФАКТ (веб)', 'АНАЛИЗ', 'ГИПОТЕЗА', 'ОТКРЫТО'] },
        source: { type: 'string' },
      }, required: ['claim', 'layer'] } },
    summary: { type: 'string' },
  }, required: ['findings', 'summary'],
}

// ── ЭКСПРЕСС: дёшево отсортировать входящую заявку ───────────────────────────
if (MODE === 'express') {
  phase('Разведка')
  const quick = await parallel([
    () => agent(`${FULL}\n\nЗАДАЧА: пройди по вебу по нише и гео и скажи, на чём в этой нише строят посыл все — то есть что стало шумом, и где свободно. Используй WebSearch.`, { label: 'ниша', phase: 'Разведка', schema: NOTES, effort: 'low' }),
    () => agent(`${FULL}\n\nЗАДАЧА: найди и бегло разбери 1–2 главных конкурентов${COMPS.length ? ' (начни с этих: ' + COMPS.join(', ') + ')' : ''}: позиционирование, чем доказывают, видна ли цена. WebSearch + WebFetch.`, { label: 'конкуренты', phase: 'Разведка', schema: NOTES, effort: 'low' }),
    () => agent(`${FULL}\n\nЗАДАЧА: по интейку — главный разрыв между «как есть» и «как могло быть». Один, самый дорогой. И почему именно он.`, { label: 'разрыв', phase: 'Разведка', schema: NOTES }),
  ])
  phase('Синтез')
  const note = await agent(
    `${FULL}\n\nМАТЕРИАЛ РАЗВЕДКИ:\n${JSON.stringify(quick.filter(Boolean), null, 1)}\n\n` +
    `ЗАДАЧА: внутренняя записка на полстраницы для Андрея и Маши. Строго: сегмент; главный диагноз (2–3 строки); ` +
    `главный разрыв и рычаг; 🔷 стоит ли браться и на какой тир реально тянет ($500 диагностика / ядро от $5k / не тянет); ` +
    `3 вопроса на звонок. С разметкой достоверности — это для нас.`,
    { label: 'экспресс-записка', phase: 'Синтез' })
  return { mode: 'express', note }
}

// ── ПОЛНЫЙ: разведка ────────────────────────────────────────────────────────
phase('Разведка')

const LENSES = [
  ['ниша и куда движется', `Что происходит в нише${NICHE ? ' «' + NICHE + '»' : ''}${GEO ? ' в гео «' + GEO + '»' : ''}: кто в выдаче, что растёт, что уходит. Найди, на чём ВСЕ строят посыл — это шум, за него не платят. И где свободно.`],
  ['язык клиента',        `Какими словами клиенты этой ниши описывают свою проблему и что ищут: формулировки запросов, темы обсуждений, вопросы. Нужны живые фразы, а не пересказ.`],
  ['боли и жалобы',       `Что клиентов в этой нише реально бесит — отзывы, жалобы, разборы. Ищи повторяющиеся претензии: на них строится отстройка.`],
  ['цены на рынке',       `Как в этой нише устроены цены и что показывают публично: вилки, пакеты, скрывают ли цену. Нужно понять, где якорится клиент.`],
  ['AI в нише',           `Кто в этой нише уже применяет AI и в чём — видимость, продажи, контент, сервис. И чего никто не делает.`],
  ['как их находят',      `Как в этой нише клиент вообще находит исполнителя: поиск, карты, соцсети, рекомендации, нейросети. Где точки видимости.`],
]

const recon = await parallel(LENSES.map(([label, task]) => () =>
  agent(`${FULL}\n\nЗАДАЧА (веб-разведка, обязательно WebSearch, при нужде WebFetch): ${task}\nВсё найденное помечай ФАКТ (веб) и давай URL. Выводы из найденного — 🔷.`,
    { label, phase: 'Разведка', schema: NOTES })))

// по агенту на конкурента, дальше — углубление тем же конвейером
const compList = COMPS.length ? COMPS : ['(имя не названо — найди 3 типовых сам и пометь ⚠️ ГИПОТЕЗА)', '(второй типовой)', '(третий типовой)']
const comps = await pipeline(compList,
  (c) => agent(`${FULL}\n\nЗАДАЧА: разбери конкурента: ${c}. Найди его сайт и соцсети (WebSearch + WebFetch). Собери: как позиционируется дословно, что обещает, чем доказывает, видна ли цена, на чём акцент, для кого он.`,
    { label: `конкурент: ${String(c).slice(0, 28)}`, phase: 'Разведка', schema: NOTES }),
  (r, c) => r ? agent(`${FULL}\n\nЧТО СОБРАНО ПРО КОНКУРЕНТА ${c}:\n${JSON.stringify(r, null, 1)}\n\n` +
      `ЗАДАЧА: отдели ОБЕЩАНИЯ от ДОКАЗАТЕЛЬСТВ. Что он заявляет, но ничем не подтверждает? Что подтверждает реально? ` +
      `И главное — что он показывает, чего НЕ показывает наш клиент, и наоборот: где у нашего клиента белое пятно, а где преимущество, которое он молчит.`,
      { label: `глубже: ${String(c).slice(0, 28)}`, phase: 'Углубление', schema: NOTES }) : null)

const WEB = JSON.stringify({ recon: recon.filter(Boolean), competitors: comps.flat().filter(Boolean) }, null, 1)

// ── синтез артефактов ───────────────────────────────────────────────────────
phase('Синтез')
const BASE = `${FULL}\n\nМАТЕРИАЛ ВЕБ-РАЗВЕДКИ (перепроверено агентами):\n${WEB}\n\n`

const ARTEFACTS = [
  ['dna_company', 'ДНК бизнеса',
   `Собери ДНК ${SEG === 'expert' ? 'практики' : 'бизнеса'}: (1) отличие в ОДНОМ предложении по формуле «помогаем [кому] достичь [результат] за счёт [чем вы уникальны]» — 3 варианта, лучший первым, и проверь по вебу, не говорит ли так же вся ниша; (2) несущая логика продукта — 3 шага, в каком порядке клиент получает результат; (3) идеальный клиент по сложности и ценности, не по обороту; (4) пруф — чем это подтверждается, чего нет — 🟥.`],
  ['dna_customer', 'ДНК клиента',
   `Собери ДНК клиента: кто он, его боли, возражения, за что реально платит, как выбирает, с чем сравнивает. Отдельным блоком — ЯЗЫК КЛИЕНТА: живые фразы (из интейка и из веб-разведки), которыми он сам описывает проблему. Этим языком потом пишутся тексты, поэтому фразы должны быть дословные, а не причёсанные.`],
  ['gaps', 'Карта разрывов',
   `Карта разрывов между «где клиент сейчас» и «где мог бы быть». Пройди по типам: качество↔восприятие, видимость, отстройка, поток, цена/маржа. Оставь только релевантные, отранжируй по величине потери, у каждого — чем подтверждается. Назови ГЛАВНЫЙ РЫЧАГ: за что браться первым и почему именно за это.`],
  ['competitors', 'Разбор конкурентов',
   `Сведи разбор конкурентов в один блок: по каждому — позиционирование, что доказывает, где слаб. Затем главное: белое пятно нашего клиента (что показывают они и не показывает он) и его непоказанное преимущество (что есть у него и нет у них). Только по данным разведки, с URL.`],
  ['ai_points', '3 AI-точки роста',
   `Ровно ТРИ точки, где AI даст клиенту деньги или время, отранжированные по эффекту: AI-видимость (находят/рекомендуют, включая нейросети и гео), AI в продажах (снятие «дорого» и «чем лучше», квалификация, доведение лида), AI-контент и прогрев. Каждую привяжи к КОНКРЕТНОМУ месту потерь из карты разрывов — не абстрактно. Эффект — направлением, без цифр.`],
  ['first_step', 'Первый шаг',
   `Что делать первым и что это даёт. Один шаг, а не список. Направление эффекта без обещания цифр. Плюс: как клиент поймёт через пару месяцев, что шаг сработал.`],
  ['offer', 'Черновик оффера (внутренний)',
   `ТОЛЬКО ДЛЯ НАС, клиенту не показываем. Заготовка Grand Slam-оффера под этого клиента: Магнит / Аватар / Цель / Интервал / Контейнер; крючок-заголовок ЕГО языком из ДНК клиента (2 варианта); value stack — что складываем в предложение; гарантия в рамках анти-гарантии (отвечаем за метод, скорость и факт внедрения, не за лиды и прибыль).`],
  ['pricing', 'Вилка цен (внутренняя)',
   `ТОЛЬКО ДЛЯ НАС. Куда вести по лестнице: диагностика $500 → ядро от $5,000 (рус. старт $5–8k, верх до $15k) → подписка $500–2,500/мес. Какую вилку называть ИМЕННО ЭТОМУ клиенту и почему — опирайся на его ответы про экономику и про порядок вложений. Чем якорить (fractional CFO/CMO $3–5k/мес, консалтинг $15–50k, «данные ≠ интеллект»). 🔷 Где риск торга и на какой тир он реально тянет. Если не тянет ядро — сказать прямо.`],
  ['session_qs', 'Вопросы к стратегической сессии',
   `ТОЛЬКО ДЛЯ НАС — план разговора на 45–60 минут по ГОТОВОМУ документу. Дай 8–12 вопросов, сгруппированных: (1) закрыть 🟥 и ⚠️ из разбора — что мы не смогли узнать; (2) проверить главный рычаг — согласен ли он, что боль там; (3) вскрыть экономику решения — что для него значит «дорого» и с чем он сравнивает; (4) вопросы, подводящие к внедрению — про готовность, сроки, кто ещё решает. У каждого вопроса одной строкой: ЗАЧЕМ мы его задаём и что услышим в ответ, если гипотеза верна.`],
]

const drafts = await parallel(ARTEFACTS.map(([key, label, task]) => () =>
  agent(`${BASE}ЗАДАЧА (артефакт «${label}»): ${task}`, { label, phase: 'Синтез' })
    .then((text) => (text ? { key, label, text } : null))))

const PACK = drafts.filter(Boolean).map((d) => `### ${d.label}\n${d.text}`).join('\n\n')

// ── проверка: три скептика с разными линзами ────────────────────────────────
phase('Проверка')
const CHECKS = [
  ['выдумки', `Ты — скептик. Найди в пакете КАЖДОЕ утверждение о клиенте или рынке, которого НЕТ ни в интейке, ни в веб-разведке. Такие утверждения — брак. По каждому: цитата, почему это выдумка, чем заменить (🟥 или переформулировать в ⚠️ ГИПОТЕЗУ). Если выдумок нет — так и скажи, не выдумывай их сам.`],
  ['анти-гарантия', `Ты — редактор по анти-гарантии. Найди каждое место, где пакет обещает КОНКРЕТНУЮ цифру или срок результата («+X%», «в N раз», «за месяц», «гарантируем рост на»). Это прямое нарушение. По каждому: цитата и как переписать в допустимое направление (продажи вырастут / затраты упадут / вас станет видно). Отдельно проверь, не проскочила ли лесть — «у вас всё отлично» там, где отстраиваться нечем.`],
  ['полнота', `Ты — критик полноты. Чего в пакете НЕ ХВАТАЕТ: какой вопрос интейка остался неиспользованным, какая линза разведки не отработана, какое утверждение осталось непроверенным, какой очевидный разрыв пропущен. Не хвали — перечисли дыры.`],
]
const audit = await parallel(CHECKS.map(([label, task]) => () =>
  agent(`${CTX}\n\n${SRC}\n\nВЕБ-РАЗВЕДКА:\n${WEB}\n\nСОБРАННЫЙ ПАКЕТ:\n${PACK}\n\nЗАДАЧА: ${task}`,
    { label, phase: 'Проверка', effort: 'high' })))

// ── правка: скептики нашли — синтез чинит, а не человек ─────────────────────
phase('Правка')
const AUDIT = audit.filter(Boolean).map((t, i) => `### Проверка «${CHECKS[i][0]}»\n${t}`).join('\n\n')
const CLIENT_FACING = ['dna_company', 'dna_customer', 'gaps', 'competitors', 'ai_points', 'first_step']
const byKey = {}
drafts.filter(Boolean).forEach((d) => { byKey[d.key] = d })

const fixed = await parallel(CLIENT_FACING.filter((k) => byKey[k]).map((k) => () =>
  agent(`${CTX}\n\n${SRC}\n\nВЕБ-РАЗВЕДКА (единственный источник веб-фактов):\n${WEB}\n\n` +
    `ТЕКУЩАЯ ВЕРСИЯ АРТЕФАКТА «${byKey[k].label}»:\n${byKey[k].text}\n\n` +
    `ОТЧЁТЫ СКЕПТИКОВ ПО ВСЕМУ ПАКЕТУ:\n${AUDIT}\n${RULES}\n\n` +
    `ЗАДАЧА: перепиши артефакт «${byKey[k].label}» начисто, внеся ВСЕ относящиеся к нему находки скептиков. ` +
    `Конкретно: убери утверждения, которых нет ни в интейке, ни в разведке; почини искажённые цитаты и цифры ` +
    `по источнику; понизь завышенные метки достоверности; убери обещания цифр результата. Ничего нового не ` +
    `добавляй — только чини. Если находка скептика к этому артефакту не относится, игнорируй её. ` +
    `Верни ПОЛНЫЙ исправленный текст артефакта, а не список правок.`,
    { label: `правка: ${byKey[k].label}`, phase: 'Правка' })
    .then((text) => (text ? { key: k, label: byKey[k].label, text } : null))))

fixed.filter(Boolean).forEach((f) => { byKey[f.key] = f })
const finalArtefacts = drafts.filter(Boolean).map((d) => byKey[d.key] || d)

log(`Правка: переписано ${fixed.filter(Boolean).length} из ${CLIENT_FACING.length} клиентских артефактов.`)
log(`Разведка: ${recon.filter(Boolean).length} линз + ${comps.flat().filter(Boolean).length} проходов по конкурентам. Артефактов: ${drafts.filter(Boolean).length}. Проверок: ${audit.filter(Boolean).length}.`)

return {
  mode: 'full', segment: SEG, client: CLIENT,
  web: { recon: recon.filter(Boolean), competitors: comps.flat().filter(Boolean) },
  artefacts: finalArtefacts,
  artefactsBeforeFix: drafts.filter(Boolean),
  audit: audit.filter(Boolean).map((t, i) => ({ lens: CHECKS[i][0], report: t })),
}
