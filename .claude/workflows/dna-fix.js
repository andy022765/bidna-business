export const meta = {
  name: 'dna-fix',
  description: 'Переписывает клиентские артефакты диагностики, внося находки скептиков',
  whenToUse: 'Точечная правка уже собранного пакета. args: {dir, clients:[...]}',
  phases: [{ title: 'Правка', detail: 'по агенту на артефакт: чинит выдумки, цитаты, метки, обещания' }],
}

const A = args || {}
const DIR = A.dir
const CLIENTS = A.clients || []
if (!DIR || !CLIENTS.length) { log('❌ нужны args.dir и args.clients'); return { error: 'bad args' } }

const KEYS = [
  ['dna_company', 'ДНК бизнеса / практики'],
  ['dna_customer', 'ДНК клиента'],
  ['gaps', 'Карта разрывов'],
  ['competitors', 'Разбор конкурентов'],
  ['ai_points', '3 AI-точки роста'],
  ['first_step', 'Первый шаг'],
]

phase('Правка')
const jobs = []
CLIENTS.forEach((c) => KEYS.forEach(([k, label]) => jobs.push({ c, k, label })))

const done = await parallel(jobs.map((j) => () =>
  agent(
`Ты — редактор платной диагностики Business Intelligence DNA. Правишь артефакт по находкам скептиков.

ПРОЧИТАЙ инструментом Read четыре файла:
1. Артефакт, который правишь:  ${DIR}/${j.c}--${j.k}.md
2. Отчёт скептика «выдумки»:    ${DIR}/${j.c}--ПРОВЕРКА-выдумки.md
3. Отчёт «анти-гарантия»:       ${DIR}/${j.c}--ПРОВЕРКА-анти-гарантия.md
4. Отчёт «полнота»:             ${DIR}/${j.c}--ПРОВЕРКА-полнота.md

ЗАДАЧА: перепиши артефакт «${j.label}» начисто, внеся ВСЕ находки скептиков, которые к нему относятся:
· убери утверждения, которых нет ни в интейке, ни в веб-разведке — особенно выдуманные проверяемые
  идентификаторы (номера лицензий, рейтинги, годы основания, количество отзывов, слоганы конкурентов);
· почини искажённые цитаты и цифры по источнику, который называет скептик;
· понизь завышенные метки: отсутствие чего-то на сайте — это 🔷 АНАЛИЗ, а не ФАКТ (веб);
· убери любые обещания конкретных цифр и сроков результата — только направление;
· где данных нет — ставь 🟥 ОТКРЫТО, а не правдоподобную догадку.

Ничего НОВОГО не добавляй — только чини. Находку, которая к этому артефакту не относится, игнорируй.

ЗАПИШИ результат инструментом Write в файл: ${DIR}/${j.c}--${j.k}.FIXED.md
Это должен быть ПОЛНЫЙ исправленный текст артефакта, а не список правок.
В ответ верни одну строку: сколько находок внёс и каких.`,
    { label: `${j.c}: ${j.label}`, phase: 'Правка' })))

log(`Готово: ${done.filter(Boolean).length} из ${jobs.length} артефактов переписано.`)
return { fixed: done.filter(Boolean).length, total: jobs.length, notes: done.filter(Boolean) }
