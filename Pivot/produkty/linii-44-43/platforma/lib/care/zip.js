const RADIUS_ZEMLI_M = 6371008.8;

// Расстояние по прямой между двумя точками, метры.
function haversineM(lat1, lon1, lat2, lon2) {
  const rad = Math.PI / 180;
  const dLat = (lat2 - lat1) * rad;
  const dLon = (lon2 - lon1) * rad;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLon / 2) ** 2;
  return 2 * RADIUS_ZEMLI_M * Math.asin(Math.min(1, Math.sqrt(a)));
}

// '11235', 11235, '11235-1234', 'NY 11235' → '11235'; иначе null.
function normZip(zip) {
  const m = String(zip == null ? '' : zip).match(/\d{5}/);
  return m ? m[0] : null;
}

function koordinaty(zip) {
  const z = normZip(zip);
  const r = z ? ZIP[z] : null;
  return r ? { zip: z, lat: r[0], lon: r[1], boro: r[2] } : null;
}

// Километры между центрами двух ZIP по прямой; null, если какого-то ZIP нет в таблице.
function rasstoyanieKm(zipA, zipB) {
  const a = koordinaty(zipA);
  const b = koordinaty(zipB);
  if (!a || !b) return null;
  return haversineM(a.lat, a.lon, b.lat, b.lon) / 1000;
}

