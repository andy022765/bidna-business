# ─── Вырезание ─────────────────────────────────────────────────────────────────
def razdel_linii(md, liniya):
    """Текст линии: от «## Линия NN — …» до следующего «## » (или конца файла)."""
    m = re.search(rf"^## {re.escape(liniya)} — .*?$\n(.*?)(?=^## |\Z)", md, re.S | re.M)
    if not m:
        upast(f"нет раздела «## {liniya} — …» в {ISTOCHNIK.name}")
    return m.group(1)


def vyrezat_blok(tekst_linii, liniya, zagolovok):
    """Блок от точного заголовка до следующего ###, ## или ---."""
    stroki = tekst_linii.split("\n")
    nachalo = [i for i, s in enumerate(stroki) if s.strip() == zagolovok]
    if not nachalo:
        upast(f"в разделе «{liniya}» нет заголовка «{zagolovok}» — его переименовали? Поправь BLOKI")
    if len(nachalo) > 1:
        upast(f"в разделе «{liniya}» заголовок «{zagolovok}» встречается {len(nachalo)} раза")
    telo = []
    for s in stroki[nachalo[0] + 1:]:
        if s.startswith("### ") or s.startswith("## ") or s.strip() == "---":
            break
        telo.append(s)
    return "\n".join(telo)


def skleit(tekst):
    """Чистим разметку и склеиваем перенесённые строки в абзацы.
    Новая строка начинается с «- », «1. », после пустой, а также строка без отступа сразу
    после пункта списка (у перенесённого пункта продолжение идёт с отступом);
    остальное — продолжение предыдущей строки."""
    tekst = re.sub(r"<!--.*?-->", "", tekst, flags=re.S)
    tekst = re.sub(r"\*\*|`", "", tekst)
    vyhod = []
    for s in tekst.split("\n"):
        chistaya = s.strip()
        if not chistaya:
            if vyhod and vyhod[-1] != "":
                vyhod.append("")
            continue
        novaya = (not vyhod or vyhod[-1] == ""
                  or re.match(r"^(- |\d+\. )", chistaya)
                  or (vyhod[-1].startswith("- ") and not s[:1].isspace()))
        if novaya:
            vyhod.append(chistaya)
        else:
            vyhod[-1] += " " + chistaya
    while vyhod and vyhod[-1] == "":
        vyhod.pop()
    while vyhod and vyhod[0] == "":
        vyhod.pop(0)
    return "\n".join(vyhod)


def zamenit(metka, tekst):
    for bylo, stalo in ZAMENY[metka]:
        if isinstance(bylo, re.Pattern):
            tekst, n = bylo.subn(stalo, tekst)
            if n != 1:
                upast(f"блок {metka}: шаблон {bylo.pattern!r} нашёлся {n} раз, ждали 1 — "
                      f"фраза в промпте Дежурного поменялась, сверь ZAMENY")
        else:
            n = tekst.count(bylo)
            if n != 1:
                upast(f"блок {metka}: фраза нашлась {n} раз, ждали 1 — промпт Дежурного "
                      f"поменялся, сверь ZAMENY:\n  «{bylo}»")
            tekst = tekst.replace(bylo, stalo)
    return tekst


