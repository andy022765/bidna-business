TYSYACHA = set("тысяча тысячи тысяч тысячу тысячей тысячам тысячами".split())
DESYATKI_1X = {v for v, (z, r) in SLOVA.items() if 10 <= z <= 19}


def chisla_slovami(tekst):
    """Все числа, записанные словами. «две с половиной тысячи» → 2500,
    «двадцать пять центов» → 25 и 0.25."""
    najdeno = []
    # Знак препинания рвёт число: «полторы тысячи, сто девяносто девять» — это 1500 и 199,
    # а не 1699. Поэтому каждый кусок между знаками разбираем отдельно.
    for kusok in re.split(r"[^\w\s]|_", tekst.lower().replace("ё", "е")):
        najdeno.extend(_chisla_v_kuske(re.findall(r"[а-я]+", kusok)))
    return najdeno


def _chisla_v_kuske(slova):
    najdeno = []
    vsego, tek, posl_razryad, v_gruppe = 0, 0, 99, False

    def sbros():
        nonlocal vsego, tek, posl_razryad, v_gruppe
        znach = None
        if v_gruppe:
            znach = vsego + tek
            najdeno.append(znach)
        vsego, tek, posl_razryad, v_gruppe = 0, 0, 99, False
        return znach

    i = 0
    while i < len(slova):
        s = slova[i]
        if s in TYSYACHA:
            vsego += (tek or 1) * 1000
            tek, posl_razryad, v_gruppe = 0, 4, True
        elif s in SLOVA:
            znach, razryad = SLOVA[s]
            # единица после единицы или после 10–19 — это уже новое число
            if v_gruppe and (razryad >= posl_razryad or (posl_razryad == 1 and razryad == 1)):
                sbros()
            tek += znach
            posl_razryad = 1 if s in DESYATKI_1X else razryad
            v_gruppe = True
        elif s == "с" and v_gruppe and i + 1 < len(slova) and slova[i + 1] == "половиной":
            tek += 0.5
            i += 1
        else:
            z = sbros()
            # «двадцать пять центов» — это ещё и $0.25
            if s.startswith("цент") and z is not None:
                najdeno.append(round(z / 100, 4))
        i += 1
    sbros()
    return najdeno


def chisla_ciframi(tekst):
    # «линии 03», «линия 04» — номера разделов промпта, а не числа для человека
    tekst = re.sub(r"[Лл]ини[яиейю]\s+\d+(\s*(и|,)\s*\d+)*", "", tekst)
    # запятая или точка между цифрами — десятичная: 1,5 и 0.25
    return [float(m.replace(",", ".")) for m in re.findall(r"\d+(?:[.,]\d+)?", tekst)]


def norm(x):
    x = round(float(x), 4)
    return int(x) if x == int(x) else x


def repliki(tekst):
    """Всё, что в «ёлочках», с учётом вложенных «…«…»…»."""
    vyhod, glubina, nachalo = [], 0, 0
    for i, ch in enumerate(tekst):
        if ch == "«":
            if glubina == 0:
                nachalo = i + 1
            glubina += 1
        elif ch == "»" and glubina:
            glubina -= 1
            if glubina == 0:
                vyhod.append(tekst[nachalo:i])
    return vyhod


# ─── Сборка ────────────────────────────────────────────────────────────────────
def main():
    global ISTOCHNIK
    ap = argparse.ArgumentParser(description="Сборка промпта Доводчика")
    ap.add_argument("--istochnik", type=Path, default=ISTOCHNIK)
    ap.add_argument("--ramka", type=Path, default=RAMKA)
    ap.add_argument("--vyhod", type=Path, default=VYHOD)
    ap.add_argument("--andrey-pishet", action="store_true",
                    help="включить строки [ANDREY_PISHET] (Вера может писать «Андрей напишет здесь же»)")
    args = ap.parse_args()
    ISTOCHNIK = args.istochnik

    if not args.istochnik.exists():
        upast(f"нет файла {args.istochnik}")
    if not args.ramka.exists():
        upast(f"нет файла {args.ramka}")
    md = args.istochnik.read_text(encoding="utf-8")
    ramka_md = args.ramka.read_text(encoding="utf-8")

    m = re.search(r"^```text\n(.*?)\n^```", ramka_md, re.S | re.M)
    if not m:
        upast(f"в {args.ramka.name} нет блока ```text с рамкой")
    ramka = m.group(1)

    # Условные строки рамки
    stroki = []
    for s in ramka.split("\n"):
        if s.startswith("[ANDREY_PISHET] "):
            if args.andrey_pishet:
                stroki.append(s[len("[ANDREY_PISHET] "):])
        elif s.startswith("[BEZ_ANDREY_PISHET] "):
            if not args.andrey_pishet:
                stroki.append(s[len("[BEZ_ANDREY_PISHET] "):])
        else:
            stroki.append(s)
    ramka = "\n".join(stroki)

    # Вырезаем, переписываем, считаем числа
    chisla = set()
    razdely = {}
    gotovye = {}
    for metka, liniya, zagolovok, zagolovok_chat in BLOKI:
        if liniya not in razdely:
            razdely[liniya] = razdel_linii(md, liniya)
        syroy = skleit(vyrezat_blok(razdely[liniya], liniya, zagolovok))
        if not syroy.strip():
            upast(f"блок «{zagolovok}» в разделе «{liniya}» пустой")
        # Числа — из ИСХОДНОГО блока (словами и цифрами), до замен
        chisla.update(norm(x) for x in chisla_slovami(syroy))
        chisla.update(norm(x) for x in chisla_ciframi(syroy))
        blok = zamenit(metka, syroy)
        for shablon, chto in GOLOS_V_BLOKAH:
            nashlos = re.search(shablon, blok)
            if nashlos:
                okrug = blok[max(0, nashlos.start() - 60):nashlos.end() + 60].replace("\n", " ")
                upast(f"блок {metka}: осталось {chto}: …{okrug}… — добавь замену в ZAMENY")
        # и цифры, которые появились после замен ($0.25, 1 час) — тоже из этого блока
        chisla.update(norm(x) for x in chisla_ciframi(blok))
        gotovye[metka] = f"{zagolovok_chat}\n{blok}"

    chisla.update(norm(x) for x in VSEGDA)
    for x in NE_RAZRESHAT:
        chisla.discard(x)

    # Подстановка в рамку
    for metka, blok in gotovye.items():
        if ramka.count("{{" + metka + "}}") != 1:
            upast(f"в рамке метка {{{{{metka}}}}} встречается {ramka.count('{{' + metka + '}}')} раз, ждали 1")
        ramka = ramka.replace("{{" + metka + "}}", blok)
    ostalos = re.findall(r"\{\{[^}]*\}\}", ramka)
    if ostalos:
        upast(f"в рамке остались незаполненные метки: {ostalos}")
    prompt = re.sub(r"\n{3,}", "\n\n", ramka).strip() + "\n"

    # Проверки итогового промпта
    for shablon, chto in STARYE_CENY:
        nashlos = re.search(shablon, prompt, re.I)
        if nashlos:
            okrug = prompt[max(0, nashlos.start() - 60):nashlos.end() + 60].replace("\n", " ")
            upast(f"старая цена или голосовое правило — {chto}: …{okrug}…")
    # «аудитория» — не «аудит»
    for nashlos in re.finditer(r"\bаудит(а|ом|у|е|ы|ов)?\b", prompt, re.I):
        # можно «не аудит», «Не «аудит»» и само правило «Слово «аудит» — только в отрицании»
        pered = prompt[max(0, nashlos.start() - 8):nashlos.start()].lower()
        if not (re.search(r"\bне\s*«?$", pered) or pered.endswith("слово «")):
            okrug = prompt[max(0, nashlos.start() - 60):nashlos.end() + 30].replace("\n", " ")
            upast(f"«аудит» без отрицания: …{okrug}…")
    chuzhie = set()
    for r in repliki(prompt):
        for x in chisla_ciframi(r):
            if norm(x) not in chisla:
                chuzhie.add((norm(x), r[:80]))
    if chuzhie:
        upast("в репликах Веры числа не из допустимых: " +
              "; ".join(f"{x} в «{r}…»" for x, r in sorted(chuzhie, key=lambda t: t[0])))

    # Запись
    args.vyhod.mkdir(parents=True, exist_ok=True)
    otpechatok = hashlib.sha256((md + ramka_md).encode("utf-8")).hexdigest()[:12]
    # Без даты: одинаковые исходники дают байт-в-байт одинаковый файл, лишних изменений нет
    shapka = (f"// СГЕНЕРИРОВАНО sobrat_prompt.py из исходников {otpechatok}. Руками не править:\n"
              f"// правь Pivot/agenty/dogonyayushchiy/PROMPT-DOGON.md или Pivot/golos/PROMPT-DEZHURNY.md\n"
              f"// и пересобери: python3 Pivot/agenty/dogonyayushchiy/sobrat_prompt.py\n")
    (args.vyhod / "prompt.generated.js").write_text(
        shapka + "module.exports = " + json.dumps(prompt, ensure_ascii=False) + ";\n", encoding="utf-8")
    spisok = sorted(chisla)
    (args.vyhod / "chisla.generated.js").write_text(
        shapka + "// Числа, которые Вере можно писать: всё числовое из вырезанных блоков (словами и цифрами)\n"
        "// плюс постоянные. Исключены: " + "; ".join(f"{k} — {v}" for k, v in NE_RAZRESHAT.items()) + "\n"
        "module.exports = " + json.dumps(spisok) + ";\n", encoding="utf-8")

    print(f"промпт: {len(prompt)} знаков, {len(prompt.encode('utf-8'))} байт, "
          f"~{len(prompt) // 3} токенов (грубо), andrey_pishet={args.andrey_pishet}")
    print(f"числа ({len(spisok)}): {', '.join(str(x) for x in spisok)}")
    print(f"записано: {args.vyhod / 'prompt.generated.js'}")
    print(f"          {args.vyhod / 'chisla.generated.js'}")


if __name__ == "__main__":
    main()
