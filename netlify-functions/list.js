// ── подпись: не пускаем дёргать дорогие шаги в обход первого ─────────────────
const SECRET = process.env.MIRROR_SECRET || process.env.ANTHROPIC_API_KEY || 'bidna-dev';
const sign = (host, ts) =>
  crypto.createHmac('sha256', SECRET).update(`${host}|${ts}`).digest('hex').slice(0, 24);
// 20 минут, а не 5: человек читает список и думает, пока идут шаги.
const checkToken = (b) => {
  const ts = Number(b.ts || 0);
  if (!ts || Math.abs(Date.now() - ts) > 20 * 60 * 1000) return false;
  return sign(clip(b.h, 80), ts) === b.tok;
};

// ── дневная квота на браузер ─────────────────────────────────────────────────
