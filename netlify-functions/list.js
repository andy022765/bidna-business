const qsig = (n, d) => crypto.createHmac('sha256', SECRET).update(`q|${n}|${d}`).digest('hex').slice(0, 16);
function readQuota(event) {
  const raw = (event.headers.cookie || '').match(/bidna_ql=([^;]+)/);
  if (!raw) return 0;
  const [n, d, s] = decodeURIComponent(raw[1]).split('.');
  if (d !== today() || qsig(n, d) !== s) return 0;
  return Number(n) || 0;
}
const quotaCookie = (n) => ({
  'set-cookie': `bidna_ql=${encodeURIComponent(`${n}.${today()}.${qsig(String(n), today())}`)}` +
    `; Path=/; Max-Age=86400; SameSite=Lax; Secure; HttpOnly`,
});

// ── чтение его страницы. Бесплатно, без модели, необязательно ────────────────
function normalize(link) {
  let s = clip(link, 300);
  if (!s) return null;
  if (!/^https?:\/\//i.test(s)) s = 'https://' + s;
  let u; try { u = new URL(s); } catch { return null; }
  if (!/^https?:$/.test(u.protocol)) return null;                    // только http(s)
  if (/^(localhost$|127\.|10\.|192\.168\.|169\.254\.|\[)/i.test(u.hostname)) return null; // не ходим внутрь
  return u;
}
const ENT = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", nbsp: ' ', laquo: '«', raquo: '»', mdash: '—' };
const unent = (s) => String(s).replace(/&(amp|lt|gt|quot|#39|nbsp|laquo|raquo|mdash);/g, (_, k) => ENT[k] || ' ');
const meta = (html, re) => { const m = html.match(re); return m ? unent(m[1]).trim() : ''; };

async function grab(url, ms) {
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), ms);
  try {
    const r = await fetch(url, { headers: { 'user-agent': UA, accept: 'text/html,*/*' }, signal: ctl.signal, redirect: 'follow' });
    const html = (await r.text()).slice(0, 900000);
    let text = html
      .replace(/<(script|style|noscript|template|svg)[\s\S]*?<\/\1>/gi, ' ')
      .replace(/<[^>]+>/g, ' ');
    text = unent(text).replace(/\s+/g, ' ').trim();
    // теги снимаем дважды: раскодированные сущности снова дают разметку (грабли Instagram)
    text = unent(text.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();
    return {
      ok: r.ok,
      title: meta(html, /<meta[^>]+property=["']og:title["'][^>]+content=["']([^"']*)["']/i) ||
             meta(html, /<title[^>]*>([\s\S]*?)<\/title>/i),
      desc: meta(html, /<meta[^>]+property=["']og:description["'][^>]+content=["']([^"']*)["']/i) ||
            meta(html, /<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)["']/i),
      text: text.slice(0, 4000),
    };
  } catch { return { ok: false, title: '', desc: '', text: '' }; }
  finally { clearTimeout(t); }
}

// ── вызов модели ─────────────────────────────────────────────────────────────
const DEADLINE = 32000;                       // стена 40с, оставляем запас на сеть
function withDeadline(p, ms) {
  return Promise.race([p, new Promise((_, rej) => setTimeout(() => rej(new Error('deadline')), ms))]);
}
// Актуальный прайс за миллион токенов (сверено 06.09.2026).
const PRICE = { [MODEL_DEEP]: [5, 25], [MODEL_FAST]: [2, 10] };
const money = (model, u) => {
  const p = PRICE[model]; if (!p || !u) return 0;
  return ((u.input_tokens || 0) + (u.cache_read_input_tokens || 0)) / 1e6 * p[0] +
         (u.output_tokens || 0) / 1e6 * p[1];
};
async function ask(client, opts) {
  const { model, ...rest } = opts;
  const use = model || MODEL_FAST;
  const req = { model: use, ...rest };
  if (use === MODEL_FAST) delete req.fallbacks;                 // Sonnet не принимает fallbacks
  const r = await client.messages.create(req);
  const cost = money(use, r.usage);
  console.log('[list$]', use, cost.toFixed(4), JSON.stringify(r.usage || {}));
  const text = (r.content || []).filter(b => b.type === 'text').map(b => b.text).join('\n');
  return { text, cost };
}
function parseJson(text) {
  const s = String(text || '');
  const a = s.indexOf('{'), b = s.lastIndexOf('}');
  if (a < 0 || b <= a) return null;
  try { return JSON.parse(s.slice(a, b + 1)); } catch {}
  try { return JSON.parse(s.slice(a, b + 1).replace(/,\s*([}\]])/g, '$1')); } catch { return null; }
}

