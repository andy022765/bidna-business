// ── ШАГ 1: старт ─────────────────────────────────────────────────────────────
function stepStart(b, event) {
  const used = readQuota(event);
  if (used >= DAILY_LIMIT) return json(429, { error: 'quota', limit: DAILY_LIMIT });
  const what = clip(b.what, 400);
  const loop = clip(b.loop, 900);
  if (what.length < 8 || loop.length < 12) return json(400, { error: 'too_short' });
  const ts = Date.now();
  const host = clip((event.headers || {}).host || 'x', 80);
  const u = normalize(b.link);
  return json(200, {
    ok: true, ts, tok: sign(host, ts), h: host,
    link: u ? u.href : null,
    left: DAILY_LIMIT - used - 1,
  }, quotaCookie(used + 1));
}

// ── ШАГ 2: читаем его страницу. Бесплатно, необязательно ─────────────────────
async function stepRead(b) {
  if (!checkToken(b)) return json(403, { error: 'bad_token' });
  const u = normalize(b.link);
  if (!u) return json(200, { ok: false });
  const g = await grab(u.href, 7000);
  const useful = (g.title + ' ' + g.desc + ' ' + g.text).trim();
  // Меньше 200 знаков — материала нет. Молчим об этом: человеку про это ни слова.
  return json(200, useful.length > 200
    ? { ok: true, title: clip(g.title, 200), desc: clip(g.desc, 400), text: clip(g.text, 3500) }
    : { ok: false });
}

