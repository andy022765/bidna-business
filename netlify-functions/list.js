// ── постфильтр: диагноз и цифры будущего. Регуляркой, а не верой в промпт ────
const BAD = [
  /\bсейчас\s+(?:у\s+вас|вы)\b/i, /\bпока\s+(?:у\s+вас|вы)\b/i, /\bраньше\s+вы\b/i,
  /\bвы\s+тер[яи]/i, /\bу\s+вас\s+нет\b/i, /\bне\s+хватает\b/i, /\bотсутству/i,
  /\bвместо\s+того,?\s+чтобы\b/i, /\bдо\s+сих\s+пор\b/i, /\bвручную\b/i,
  /\+\s*\d+\s*%/, /\bв\s+\d+\s*раз[аеы]?\b/i, /\bокуп(?:ит|аем)/i, /\bвырастет\b/i, /\bгарантиру/i,
];
const clean = (s) => BAD.some(re => re.test(String(s || '')));

exports.handler = async (event) => {
  if (event.httpMethod !== 'POST') return json(405, { error: 'method' });
  let b; try { b = JSON.parse(event.body || '{}'); } catch { return json(400, { error: 'body' }); }
  if (clip(b.website, 200)) return json(400, { error: 'bot' });          // honeypot

  const step = clip(b.step, 16);
  if (step === 'start') return stepStart(b, event);

  const key = process.env.ANTHROPIC_API_KEY;
  if (!key && step !== 'read') return json(503, { error: 'no_key' });
  const client = key ? new Anthropic({ apiKey: key }) : null;

  try {
    if (step === 'read')  return await stepRead(b);
    if (step === 'band1') {
      const r = await stepBand1(client, b, Number(b.part) || 1);
      const d = JSON.parse(r.body);
      if (d.ok && (d.band1 || []).some(w => clean(w.does) || clean(w.when) || clean(w.gives)))
        console.log('[list!] постфильтр поймал диагноз в полосе 01');
      return r;
    }
    if (step === 'rest')  return await stepRest(client, b);
    if (step === 'extra') return await stepExtra(client, b);
    return json(400, { error: 'bad_step' });
  } catch (e) {
    console.log('[list x]', step, String(e && e.message).slice(0, 200));
    return json(e && e.message === 'deadline' ? 504 : 502, { error: 'failed', step });
  }
};
